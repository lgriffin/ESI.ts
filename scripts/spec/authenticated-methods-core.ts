/**
 * Which public methods of each custom domain client need a token (#675),
 * found by running them: every method is called on a client whose ApiClient
 * holds no token, over a transport that answers `[]`. One that the pipeline
 * refuses with NO_AUTH_TOKEN before the wire needs a token; one that reaches
 * the transport (or the rate limiter, which comes after the token check) does
 * not. Running the methods, rather than reading them, follows aliases and
 * helpers that delegate to another client's endpoints.
 *
 * `npm run generate:public-clients` writes the result to
 * src/clients/authenticatedMethods.generated.ts, which `PublicClient` reads;
 * tests/tdd/clients/publicClient.test.ts fails when the file is stale.
 */
import { ApiClient } from '../../src/core/ApiClient';
import {
  CLIENT_TYPES,
  createClientInstance,
  type ApiClientType,
} from '../../src/clients/ClientRegistry';

export const AUTHENTICATED_METHODS_PATH =
  'src/clients/authenticatedMethods.generated.ts';

type Outcome = 'token' | 'public' | 'unknown';

async function outcomeOf(
  call: () => unknown,
  fetched: () => boolean,
): Promise<{ outcome: Outcome; detail: string }> {
  let error: unknown;
  try {
    const result = call() as
      | AsyncIterable<unknown>
      | Promise<unknown>
      | undefined;
    if (result && Symbol.asyncIterator in Object(result)) {
      await (result as AsyncIterable<unknown>)[Symbol.asyncIterator]().next();
    } else {
      await result;
    }
  } catch (err) {
    error = err;
  }
  const message = error instanceof Error ? error.message : String(error);
  if (error !== undefined && message.includes('NO_AUTH_TOKEN')) {
    return { outcome: 'token', detail: message };
  }
  if (fetched() || message.includes('No rate limiter')) {
    return { outcome: 'public', detail: message };
  }
  return { outcome: 'unknown', detail: message };
}

/** The public methods a client class declares itself, in declaration order. */
function ownMethods(client: object): string[] {
  const proto = Object.getPrototypeOf(client) as Record<string, unknown>;
  return Object.getOwnPropertyNames(proto).filter(
    (name) =>
      name !== 'constructor' &&
      !name.startsWith('_') &&
      typeof Object.getOwnPropertyDescriptor(proto, name)?.value ===
        'function',
  );
}

export interface Classification {
  /** Per domain, the methods that need a token, sorted. */
  readonly authenticated: Readonly<Record<ApiClientType, readonly string[]>>;
  /** Methods neither outcome could be read for, with the error each threw. */
  readonly unknown: readonly string[];
}

export async function classifyMethods(): Promise<Classification> {
  const authenticated = {} as Record<ApiClientType, string[]>;
  const unknown: string[] = [];
  for (const name of CLIENT_TYPES) {
    let fetched = false;
    const api = new ApiClient('classify', 'https://esi.evetech.net');
    api.setValidateResponse(false);
    api.setFetch(() => {
      fetched = true;
      return Promise.resolve(
        new Response('[]', {
          status: 200,
          headers: { 'content-type': 'application/json' },
        }),
      );
    });
    const client = createClientInstance(name, api) as unknown as Record<
      string,
      (...args: unknown[]) => unknown
    >;
    const list: string[] = [];
    for (const method of ownMethods(client)) {
      // Ids first; a method that joins a list gets arrays on the second try.
      let result = { outcome: 'unknown' as Outcome, detail: '' };
      for (const arg of [1, [1]]) {
        fetched = false;
        result = await outcomeOf(
          () => client[method]!(...Array.from({ length: 6 }, () => arg)),
          () => fetched,
        );
        if (result.outcome !== 'unknown') break;
      }
      if (result.outcome === 'token') list.push(method);
      if (result.outcome === 'unknown') {
        unknown.push(`${name}.${method}: ${result.detail}`);
      }
    }
    list.sort();
    authenticated[name] = list;
  }
  return { authenticated, unknown };
}

export function renderAuthenticatedMethods(
  authenticated: Readonly<Record<string, readonly string[]>>,
): string {
  const rows = Object.entries(authenticated)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, methods]) => {
      const union =
        methods.length === 0
          ? 'never'
          : methods.map((m) => `'${m}'`).join(' | ');
      return `  readonly ${name}: ${union};`;
    });
  return `// Auto-generated by npm run generate:public-clients — do not edit manually
// The public methods of each custom domain client that need a token, found by
// running them on a client that holds none (scripts/spec/authenticated-methods-core.ts).
// PublicClient leaves them out; tests/tdd/clients/publicClient.test.ts fails when this is stale.

export interface AuthenticatedMethods {
${rows.join('\n')}
}
`;
}
