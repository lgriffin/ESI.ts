/**
 * Route table emitter (option D step 2, #671): the facts the spec states
 * about each operation (method, path template, scopes, pagination,
 * deprecation, text and empty responses), as one frozen row per
 * operationId, for the custom endpoint maps in src/core/endpoints.
 *
 * src/core may not import src/generated (lint:layers), so the custom maps
 * cannot read the `*Meta` objects. This module imports nothing, so it sits
 * in src/core/endpoints beside esi-scopes.generated.ts, and `fromOperation`
 * (src/core/endpoints/fromOperation.ts) builds definitions from it.
 *
 * Pure: takes the operations generateOperations returned, returns source
 * text. scripts/spec/spec-generate.ts formats and writes or checks it.
 */
import type { GeneratedOperation } from './spec-generate-core';

/** The module it writes. */
export const ROUTES_OUT_PATH = 'src/core/endpoints/esi-operations.generated.ts';

function row(op: GeneratedOperation): string {
  const fields: string[] = [
    `method: ${JSON.stringify(op.method)}`,
    `path: ${JSON.stringify(op.path)}`,
    `scopes: ${JSON.stringify(op.scopes)}`,
    `pagination: ${JSON.stringify(op.pagination)}`,
    `deprecated: ${op.deprecated}`,
  ];
  if (op.deprecation && Object.keys(op.deprecation).length > 0) {
    fields.push(`deprecation: ${JSON.stringify(op.deprecation)}`);
  }
  if (op.textResponse) {
    fields.push(`textResponse: ${JSON.stringify(op.textResponse)}`);
  }
  if (op.emptyWhenNoContent) fields.push('emptyWhenNoContent: true');
  return `  ${op.operationId}: { ${fields.join(', ')} },`;
}

export function generateRouteTable(
  operations: readonly GeneratedOperation[],
  specPath: string,
): string {
  const sorted = [...operations].sort((a, b) =>
    a.operationId.localeCompare(b.operationId),
  );
  return `// Auto-generated by npm run spec:generate from ${specPath} — do not edit manually
// One row per operation (${sorted.length}): what the spec says about the route.
// The custom endpoint maps build their definitions from it with fromOperation
// (guides/CLIENT-ARCHITECTURE.md, plan step 2).

export const esiOperations = {
${sorted.map(row).join('\n')}
} as const;

/** The operationId of an ESI operation the generator knows. */
export type EsiOperationId = keyof typeof esiOperations;
`;
}
