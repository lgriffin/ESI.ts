// Tree shaking
// ---------------------------------------------------------------------------

/** The parts of esbuild's API the check uses. */
export interface EsbuildLike {
  buildSync(options: Record<string, unknown>): {
    outputFiles?: Array<{ text: string }>;
    metafile?: { inputs: Record<string, unknown> };
  };
}

export interface TreeShakeOptions {
  consumerDir: string;
  esbuild: EsbuildLike;
  packageName: string;
  /** A named import from the sub-path that must stay small. */
  light: { subpath: string; name: string };
  /** A named import from the sub-path whose code must not come along. */
  heavy: { subpath: string; name: string };
  /** A string only the heavy sub-path's code contains. */
  marker: string;
  /** The light bundle's ceiling, in bytes. */
  maxBytes: number;
  external: readonly string[];
}

export interface TreeShakeResult {
  ok: boolean;
  problems: string[];
  lightBytes: number;
  heavyBytes: number;
}

/**
 * Bundle `import { name } from '<sub-path>'` for the light and the heavy
 * sub-path, as an application bundler would (esbuild, ES module output,
 * minified, dependencies external). The heavy bundle is the control: it must
 * contain the marker, or the marker proves nothing. The light bundle must not
 * contain the marker, must not include the heavy sub-path's entry file, and
 * must stay under `maxBytes`.
 */
export function treeShakeCheck(options: TreeShakeOptions): TreeShakeResult {
  const bundle = (entry: { subpath: string; name: string }) => {
    const specifier = specifierFor(options.packageName, entry.subpath);
    const result = options.esbuild.buildSync({
      stdin: {
        contents: `import { ${entry.name} } from '${specifier}';\nconsole.log(${entry.name});\n`,
        resolveDir: options.consumerDir,
        loader: 'js',
      },
      bundle: true,
      write: false,
      format: 'esm',
      platform: 'node',
      minify: true,
      metafile: true,
      logLevel: 'silent',
      external: [...options.external],
    });
    return {
      text: result.outputFiles?.[0]?.text ?? '',
      inputs: Object.keys(result.metafile?.inputs ?? {}).map((f) =>
        f.split(path.sep).join('/'),
      ),
    };
  };

  const light = bundle(options.light);
  const heavy = bundle(options.heavy);
  const problems: string[] = [];
  const lightSpecifier = specifierFor(
    options.packageName,
    options.light.subpath,
  );
  const heavySpecifier = specifierFor(
    options.packageName,
    options.heavy.subpath,
  );

  if (!heavy.text.includes(options.marker)) {
    problems.push(
      `control: the ${heavySpecifier} bundle does not contain the marker ${JSON.stringify(options.marker)}, so its absence proves nothing`,
    );
  }
  if (light.text.includes(options.marker)) {
    problems.push(
      `${lightSpecifier} bundle contains ${JSON.stringify(options.marker)} from ${heavySpecifier}`,
    );
  }
  const heavyEntry = importTarget(
    options.consumerDir,
    options.packageName,
    options.heavy.subpath,
  );
  if (!heavyEntry || !heavy.inputs.some((f) => f.endsWith(heavyEntry))) {
    problems.push(
      `control: the ${heavySpecifier} bundle does not include its entry file ${heavyEntry ?? '(no import target in exports)'}`,
    );
  } else if (light.inputs.some((f) => f.endsWith(heavyEntry))) {
    problems.push(
      `${lightSpecifier} bundle includes ${heavyEntry}, the entry file of ${heavySpecifier}`,
    );
  }
  if (light.text.length > options.maxBytes) {
    problems.push(
      `${lightSpecifier} bundle is ${light.text.length} B, over its ${options.maxBytes} B ceiling`,
    );
  }
  return {
    ok: problems.length === 0,
    problems,
    lightBytes: light.text.length,
    heavyBytes: heavy.text.length,
  };
}

/**
 * `node_modules/<package>/<file>` for the `import` target of a sub-path in
 * the installed package's `exports` map, or null when it has none.
 */
export function importTarget(
  consumerDir: string,
  packageName: string,
  subpath: string,
): string | null {
  const manifest = JSON.parse(
    readFileSync(
      path.join(consumerDir, 'node_modules', packageName, 'package.json'),
      'utf8',
    ),
  ) as { exports?: Record<string, unknown> };
  const entry = manifest.exports?.[subpath];
  let target: unknown =
    entry && typeof entry === 'object'
      ? (entry as Record<string, unknown>).import
      : undefined;
  if (target && typeof target === 'object') {
    target = (target as Record<string, unknown>).default;
  }
  return typeof target === 'string'
    ? `node_modules/${packageName}/${target.replace(/^\.\//, '')}`
    : null;
}
