// Type-check cells
// ---------------------------------------------------------------------------

export const PROBE_DIR = 'probe';

/**
 * The generated probe for one module format. The ES module probe imports
 * every sub-path as a namespace and asserts that no namespace type has a
 * `default` member; the runtime ES module has none. The CommonJS probe uses
 * `import x = require()`, which resolves through the `require` condition
 * under every resolution, including bundler with `module: preserve`.
 */
export function probeSource(
  format: ModuleFormat,
  packageName: string,
  subpaths: readonly string[],
): string {
  const lines = [
    `// Generated by scripts/consumer-contract-core.ts for ${packageName}.`,
  ];
  subpaths.forEach((subpath, i) => {
    const specifier = specifierFor(packageName, subpath);
    lines.push(
      format === 'esm'
        ? `import * as m${i} from '${specifier}';`
        : `import m${i} = require('${specifier}');`,
    );
  });
  lines.push(
    "type HasDefault<M> = 'default' extends keyof M ? true : false;",
    '// Each sub-path exports something a consumer can name.',
    'type HasExports<M> = [keyof M] extends [never] ? false : true;',
  );
  const tuple = (type: string) =>
    subpaths.map((_, i) => `${type}<typeof m${i}>`).join(', ');
  const values = (value: string) => subpaths.map(() => value).join(', ');
  lines.push(
    `export const hasExports: [${tuple('HasExports')}] = [${values('true')}];`,
  );
  if (format === 'esm') {
    lines.push(
      '// An ES module has no default export unless it declares one.',
      `export const noSynthesisedDefault: [${tuple('HasDefault')}] = [${values('false')}];`,
    );
  }
  return `${lines.join('\n')}\n`;
}

export function probeFile(format: ModuleFormat): string {
  return `${PROBE_DIR}/${format === 'esm' ? 'probe.mts' : 'probe.cts'}`;
}

/** Write both probes into `consumerDir/probe/`. */
export function writeProbes(
  consumerDir: string,
  packageName: string,
  subpaths: readonly string[],
): void {
  mkdirSync(path.join(consumerDir, PROBE_DIR), { recursive: true });
  for (const format of ['esm', 'cjs'] as const) {
    writeFileSync(
      path.join(consumerDir, probeFile(format)),
      probeSource(format, packageName, subpaths),
    );
  }
}

export interface CellOptions {
  /** Extra consumer files for the cell, relative to the consumer directory. */
  files?: readonly string[];
  /** `compilerOptions.types`; `[]` when `@types/node` is not installed. */
  types?: readonly string[];
}

/** The tsconfig for one cell. Nothing is emitted. */
export function cellTsconfig(
  cell: Cell,
  options: CellOptions = {},
): Record<string, unknown> {
  const module =
    cell.resolution === 'bundler'
      ? // `preserve` keeps `import x = require()` legal in the .cts probe, and
        // resolves it through `require` as a bundler would.
        cell.format === 'cjs'
        ? 'preserve'
        : 'esnext'
      : cell.resolution;
  return {
    compilerOptions: {
      target: 'es2022',
      module,
      moduleResolution: cell.resolution,
      strict: true,
      skipLibCheck: false,
      noEmit: true,
      // The consumers read `@lgriffin/esi.ts/package.json`.
      resolveJsonModule: true,
      types: [...(options.types ?? ['node'])],
    },
    files: [probeFile(cell.format), ...(options.files ?? [])],
  };
}

export interface CellResult {
  cell: Cell;
  ok: boolean;
  output: string;
}

/**
 * Type-check one cell with the `tsc` of the TypeScript installed in the
 * consumer (or `tsc`, when given). Spawns the CLI rather than calling the
 * compiler API: TypeScript 7 ships no stable JavaScript API.
 */
export function typeCheckCell(
  consumerDir: string,
  cell: Cell,
  options: CellOptions & { tsc?: string } = {},
): CellResult {
  const config = `tsconfig.${cell.id}.json`;
  writeFileSync(
    path.join(consumerDir, config),
    `${JSON.stringify(cellTsconfig(cell, options), null, 2)}\n`,
  );
  const tsc =
    options.tsc ??
    path.join(consumerDir, 'node_modules', 'typescript', 'bin', 'tsc');
  const result = spawnSync(process.execPath, [tsc, '-p', config], {
    cwd: consumerDir,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error) throw result.error;
  return {
    cell,
    ok: result.status === 0,
    output: `${result.stdout ?? ''}${result.stderr ?? ''}`.trim(),
  };
}

// ---------------------------------------------------------------------------
// Runtime probe
// ---------------------------------------------------------------------------

/** An ES module script that loads every sub-path through require and import. */
export function runtimeProbeSource(
  packageName: string,
  subpaths: readonly string[],
): string {
  return `// Generated by scripts/consumer-contract-core.ts.
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const specifiers = ${JSON.stringify(subpaths.map((s) => specifierFor(packageName, s)))};
const failures = [];
for (const specifier of specifiers) {
  for (const [condition, load] of [
    ['require', async () => require(specifier)],
    ['import', () => import(specifier)],
  ]) {
    try {
      const mod = await load();
      const names = Object.keys(mod).filter((k) => k !== 'default' && k !== '__esModule');
      if (names.length === 0) failures.push(\`\${specifier} (\${condition}) exports nothing\`);
    } catch (err) {
      failures.push(\`\${specifier} (\${condition}): \${err && err.code ? err.code + ' ' : ''}\${err instanceof Error ? err.message.split('\\n')[0] : String(err)}\`);
    }
  }
}
if (failures.length > 0) {
  console.error(failures.join('\\n'));
  process.exit(1);
}
console.log(\`runtime: \${specifiers.length} sub-paths load through require and import\`);
`;
}

export function runRuntimeProbe(
  consumerDir: string,
  packageName: string,
  subpaths: readonly string[],
): { ok: boolean; output: string } {
  const file = path.join(consumerDir, PROBE_DIR, 'runtime.mjs');
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, runtimeProbeSource(packageName, subpaths));
  const result = spawnSync(process.execPath, [file], {
    cwd: consumerDir,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  if (result.error) throw result.error;
  return {
    ok: result.status === 0,
    output: `${result.stdout ?? ''}${result.stderr ?? ''}`.trim(),
  };
}

