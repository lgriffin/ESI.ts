/**
 * The oldest TypeScript the package supports. zod 4's declarations use
 * `NoInfer`, added in TypeScript 5.4, and the `cjs-bundler` cell needs
 * `module: preserve`, also 5.4. Declared in README.md and
 * guides/SEMVER.md; raising it is an environment change.
 */
export const OLDEST_TYPESCRIPT = '5.4.5';

export type ModuleFormat = 'esm' | 'cjs';
export type Resolution = 'node16' | 'nodenext' | 'bundler';

export interface Cell {
  id: string;
  format: ModuleFormat;
  resolution: Resolution;
}

export const CELLS: readonly Cell[] = (
  ['node16', 'nodenext', 'bundler'] as const
).flatMap((resolution) =>
  (['esm', 'cjs'] as const).map((format) => ({
    id: `${format}-${resolution}`,
    format,
    resolution,
  })),
);

export function specifierFor(packageName: string, subpath: string): string {
  return subpath === '.' ? packageName : `${packageName}/${subpath.slice(2)}`;
}

// ---------------------------------------------------------------------------
// The exports map
// ---------------------------------------------------------------------------

/** Differences between the packed `exports` keys and the documented list. */
export function exportsProblems(
  manifest: { exports?: unknown },
  documented: readonly string[],
): string[] {
  const exportsMap =
    manifest.exports && typeof manifest.exports === 'object'
      ? (manifest.exports as Record<string, unknown>)
      : {};
  const packed = Object.keys(exportsMap).filter((k) => k !== './package.json');
  return [
    ...documented
      .filter((s) => !packed.includes(s))
      .map((s) => `documented sub-path ${s} is missing from exports`),
    ...packed
      .filter((s) => !documented.includes(s))
      .map((s) => `exports has undocumented sub-path ${s}`),
  ];
}

